def is_market_holiday(day, market):
    iso = day.isoformat() if hasattr(day, 'isoformat') else str(day)
    if market == 'Thai':
        return iso in THAI_HOLIDAYS
    if market == 'US':
        return iso in US_HOLIDAYS
    return False


def is_trading_day(day, market):
    if market == 'Crypto':
        return True
    return day.weekday() < 5 and not is_market_holiday(day, market)
